import type { ObsidianPluginVitestConfigContext } from '@mnaoumov/obsidian-dev-toolkit/test-runners/vitest-config';
import type { TestProjectConfiguration } from 'vitest/config';

import { defineObsidianPluginVitestConfig } from '@mnaoumov/obsidian-dev-toolkit/test-runners/vitest-config';
import { fileURLToPath } from 'node:url';

/**
 * The demo-vault button suite. It drives a real desktop Obsidian like the desktop project, but opens a
 * copy of the in-repo `demo-vault/` rather than an empty vault — hence its own `globalSetup` — and needs
 * its own file suffix so the desktop project does not also collect it and open it against a vault with no
 * notes in it.
 */
const DEMO_VAULT_TEST_FILES = 'src/**/*.demo-vault.integration.test.ts';

/**
 * One `it` per note runs every button in that note, and each button re-opens the note, walks the preview
 * to find itself and then waits for a result. A note with several buttons blows past the desktop
 * project's 30s default — which fails the whole note with a bare vitest timeout instead of naming the
 * button that actually misbehaved.
 */
const DEMO_VAULT_TIMEOUT_IN_MILLISECONDS = 600_000;

/**
 * Where every `.svelte` / `.vue` import in a unit test's module graph is sent. Compiling a single-file
 * component is the bundler's job, and the plugin that does it is a dependency only of the bundler that
 * was chosen — so a unit test that imports the plugin's own code would otherwise fail on a file vitest
 * cannot transform. Absolute, because a vite alias replacement is resolved from the project root rather
 * than from this file.
 */
const FRAMEWORK_COMPONENT_STUB_PATH = fileURLToPath(new URL('framework-component-stub.ts', import.meta.url));

/**
 * Where every `.wasm` import in a unit test's module graph is sent, for the same reason as the component
 * stub above. Vitest resolves a `.wasm` through vite's own WebAssembly helper, which fetches it from a
 * URL that exists only under a dev server — so a unit test that imports the plugin's own code fails on
 * `Failed to parse URL` before it runs a single assertion.
 */
const WASM_MODULE_STUB_PATH = fileURLToPath(new URL('wasm-module-stub.ts', import.meta.url));

/**
 * Where every stylesheet import in a unit test's module graph is sent. `src/main.ts` imports one for its
 * side effect, and on the `tailwind` styling the file it names is generated by the first build — so a
 * unit test run on a fresh clone would otherwise fail to resolve it.
 */
const STYLESHEET_STUB_PATH = fileURLToPath(new URL('stylesheet-stub.ts', import.meta.url));

export const config = defineObsidianPluginVitestConfig({
  customProjects(context: ObsidianPluginVitestConfigContext): TestProjectConfiguration[] {
    return [
      {
        test: {
          ...context.desktop,
          globalSetup: ['./scripts/demo-vault-global-setup.ts'],
          include: [DEMO_VAULT_TEST_FILES],
          name: 'integration-tests:demo-vault',
          testTimeout: DEMO_VAULT_TIMEOUT_IN_MILLISECONDS
        }
      }
    ];
  },
  // `^.+` is load-bearing, not decoration: a vite alias built from a RegExp replaces only the part the
  // Pattern MATCHED, so `/\.svelte$/` rewrites the extension and leaves the rest of the specifier glued
  // To the front of the stub path. The pattern has to cover the whole id.
  editContext(context: ObsidianPluginVitestConfigContext): void {
    context.unitTests.alias = [
      { find: /^.+\.(?:svelte|vue)$/u, replacement: FRAMEWORK_COMPONENT_STUB_PATH },
      { find: /^.+\.(?:css|scss)$/u, replacement: STYLESHEET_STUB_PATH },
      // Two patterns because two bundlers do not write the import plainly: vite asks for the asset's URL
      // (`./module.wasm?url`) and parcel uses a scheme (`data-url:./module.wasm`).
      { find: /^.+\.wasm(?:\?.*)?$/u, replacement: WASM_MODULE_STUB_PATH },
      { find: /^data-url:.+$/u, replacement: WASM_MODULE_STUB_PATH }
    ];
  }
});
